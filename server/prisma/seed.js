function parseCurrency(str) {
  if (!str || str.trim() === '' || str.trim() === '$  -') return 0;
  return parseFloat(str.replace(/[^0-9.]/g, '')) || 0;
}

function parseCSVLine(text) {
  const result = [];
  let current = '';
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (char === '"') {
      inQuotes = !inQuotes;
    } else if (char === ',' && !inQuotes) {
      result.push(current.trim());
      current = '';
    } else {
      current += char;
    }
  }
  result.push(current.trim());
  return result;
}

